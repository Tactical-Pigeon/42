#include "ft_rush02.h"

int	ft_validate_input(char *num)
{
	int	i;

	i = 0;
	if (num[i] == '\0')
		return (0);
	while (num[i])
	{
		if (num[i] < '0' || num[i] > '9')
			return (0);
		i++;
	}
	return (1);
}
